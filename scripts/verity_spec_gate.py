#!/usr/bin/env python3
"""Fail closed on requirement trace, OpenAPI, schema and migration drift.

Contract baselines are intentionally reviewable snapshots, not generated by CI.
Refresh them only with --write-baseline after reviewing the actual API/schema diff.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any


SPEC_NAMES = (
    "01-PRD.md",
    "02-TRD.md",
    "03-APPFLOW.md",
    "04-UI-UX-DESIGN-BRIEF.md",
    "05-BACKEND-SCHEMA.md",
    "06-IMPLEMENTATION-PLAN.md",
)
BASELINE = "docs/verity/specs/contract-baseline.json"
DEFAULT_OPENAPI = "docs/verity/evidence/spec-driven-20261011/openapi.json"
DEFAULT_SCHEMA = "docs/verity/evidence/spec-driven-20261011/schema-catalog.json"


def canonical_sha(value: Any) -> str:
    data = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(data.encode("utf-8")).hexdigest()


def api_contract(document: dict[str, Any]) -> dict[str, Any]:
    if not str(document.get("openapi", "")).startswith("3."):
        raise ValueError("OpenAPI 3.x document required")
    operations: dict[str, Any] = {}
    for path, methods in document["paths"].items():
        for method, operation in methods.items():
            if method.lower() not in {"get", "post", "put", "patch", "delete", "head", "options"}:
                continue
            operations[f"{method.upper()} {path}"] = {
                key: operation.get(key)
                for key in ("parameters", "requestBody", "responses", "security", "x-api-key-scopes")
            }
    if not operations:
        raise ValueError("OpenAPI contains no operations")
    return {
        "operations": operations,
        "schemas": document.get("components", {}).get("schemas", {}),
        "security_schemes": document.get("components", {}).get("securitySchemes", {}),
    }


def schema_contract(document: dict[str, Any]) -> dict[str, Any]:
    tables = document.get("tables")
    if not isinstance(tables, list) or not tables:
        raise ValueError("empty database schema catalog")
    if len({item["name"] for item in tables}) != len(tables):
        raise ValueError("duplicate table in database schema catalog")
    return {"alembic_revision": document.get("alembic_revision"), "tables": tables}


def migration_head(root: Path) -> str:
    revisions: dict[str, tuple[str, ...]] = {}
    for file in (root / "backend/alembic/versions").glob("*.py"):
        values: dict[str, Any] = {}
        for node in ast.parse(file.read_text()).body:
            if isinstance(node, ast.Assign) and len(node.targets) == 1:
                target = node.targets[0]
                if isinstance(target, ast.Name) and target.id in {"revision", "down_revision"}:
                    values[target.id] = ast.literal_eval(node.value)
        revision = values.get("revision")
        down = values.get("down_revision")
        if not isinstance(revision, str) or revision in revisions:
            raise ValueError(f"missing/duplicate Alembic revision: {file.name}")
        parents = () if down is None else (down,) if isinstance(down, str) else tuple(down)
        revisions[revision] = parents
    if not revisions:
        raise ValueError("no Alembic migrations")
    children = {parent for parents in revisions.values() for parent in parents}
    if not children.issubset(revisions):
        raise ValueError(f"missing Alembic parent: {sorted(children - revisions.keys())}")
    heads = sorted(revisions.keys() - children)
    if len(heads) != 1:
        raise ValueError(f"expected one Alembic head, found {heads}")
    visited: set[str] = set()
    pending = [heads[0]]
    while pending:
        revision = pending.pop()
        if revision in visited:
            raise ValueError("Alembic migration cycle or diamond")
        visited.add(revision)
        pending.extend(revisions[revision])
    if visited != revisions.keys():
        raise ValueError("disconnected Alembic migration graph")
    return heads[0]


def trace_contract(root: Path, api_paths: set[str] | None = None) -> dict[str, Any]:
    directory = root / "docs/verity/specs"
    for name in SPEC_NAMES:
        path = directory / name
        if not path.is_file() or len(path.read_text().strip()) < 300:
            raise ValueError(f"missing/empty specification: {name}")
    prd = set(re.findall(r"\bPRD-\d{3}\b", (directory / SPEC_NAMES[0]).read_text()))
    trd = set(re.findall(r"\bTRD-\d{3}\b", (directory / SPEC_NAMES[1]).read_text()))
    flows = set(re.findall(r"\bFLOW-\d{3}\b", (directory / SPEC_NAMES[2]).read_text()))
    document = json.loads((directory / "traceability.json").read_text())
    rows = document["rows"]
    ids = [row["prd"] for row in rows]
    if len(ids) != len(set(ids)) or set(ids) != prd:
        raise ValueError(f"traceability PRD coverage mismatch: missing={sorted(prd-set(ids))} extra={sorted(set(ids)-prd)}")
    if trd != {row["trd"] for row in rows}:
        raise ValueError("TRD coverage mismatch")
    mapped_flows = {flow for row in rows for flow in row.get("flows", [row["flow"]])}
    if not flows.issubset(mapped_flows):
        raise ValueError(f"unmapped AppFlow IDs: {sorted(flows-mapped_flows)}")
    required = ("ui", "api", "db_model", "code", "tests", "release_gate", "status", "evidence")
    for row in rows:
        if row["trd"] not in trd or row["flow"] not in flows:
            raise ValueError(f"unknown linked ID in {row['prd']}")
        if row["flow"] not in row.get("flows", [row["flow"]]) or not set(row.get("flows", [row["flow"]])).issubset(flows):
            raise ValueError(f"unknown AppFlow link in {row['prd']}")
        if any(not row.get(key) for key in required if key != "evidence"):
            raise ValueError(f"incomplete trace row {row['prd']}")
        if row["status"] not in {"PARTIAL", "BLOCKED", "VERIFIED"}:
            raise ValueError(f"invalid status in {row['prd']}")
        if row["status"] == "VERIFIED" and not row["evidence"]:
            raise ValueError(f"unproved VERIFIED row {row['prd']}")
        for key in ("ui", "code", "tests", "evidence"):
            for name in row[key]:
                if not (root / name).is_file():
                    raise ValueError(f"missing {key} path for {row['prd']}: {name}")
        if api_paths is not None:
            for path in row["api"]:
                if path not in api_paths:
                    raise ValueError(f"unmapped public API path for {row['prd']}: {path}")
    return {"requirements": len(rows), "flows": len(flows), "partial": sum(row["status"] == "PARTIAL" for row in rows), "blocked": sum(row["status"] == "BLOCKED" for row in rows)}


def run(root: Path, openapi: Path, schema: Path, write_baseline: bool) -> dict[str, Any]:
    head = migration_head(root)
    api = api_contract(json.loads(openapi.read_text()))
    trace = trace_contract(root, {operation.split(" ", 1)[1] for operation in api["operations"]})
    database = schema_contract(json.loads(schema.read_text()))
    if database["alembic_revision"] != head:
        raise ValueError(f"live DB revision {database['alembic_revision']} differs from migration head {head}")
    actual = {
        "migration_head": head,
        "api_sha256": canonical_sha(api),
        "schema_sha256": canonical_sha(database),
        "api_operations": len(api["operations"]),
        "schema_tables": len(database["tables"]),
    }
    target = root / BASELINE
    if write_baseline:
        target.write_text(json.dumps(actual, indent=2, sort_keys=True) + "\n")
    else:
        expected = json.loads(target.read_text())
        if actual != expected:
            raise ValueError(f"API/schema/migration drift; expected {expected}, actual {actual}. Review changes and refresh baseline explicitly")
    return {"status": "PASS", "trace": trace, "contracts": actual}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--openapi", type=Path)
    parser.add_argument("--schema", type=Path)
    parser.add_argument("--write-baseline", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        result = run(root, args.openapi or root / DEFAULT_OPENAPI, args.schema or root / DEFAULT_SCHEMA, args.write_baseline)
    except (OSError, ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
        print(json.dumps({"status": "FAIL", "error": str(exc)}), file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
